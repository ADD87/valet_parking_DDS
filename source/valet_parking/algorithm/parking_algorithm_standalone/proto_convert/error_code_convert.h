/**
 * @brief Status message containing error code and description
 *
 * Replaces apollo::common::StatusPb
 */
struct StatusPb {
  ErrorCode error_code = ErrorCode::OK;  ///< Error code
  std::string msg = "";                   ///< Error message description

  // Constructor for convenience
  StatusPb() = default;
  StatusPb(ErrorCode code, const std::string& message)
      : error_code(code), msg(message) {}

  // Check if status is OK
  bool ok() const { return error_code == ErrorCode::OK; }

  // Get error code as integer
  int32_t code() const { return static_cast<int32_t>(error_code); }
};

/**
 * @brief Helper function to create a StatusPb
 */
inline StatusPb MakeStatus(ErrorCode code, const std::string& msg = "") {
  return StatusPb(code, msg);
}

/**
 * @brief Helper function to get error code name as string (for debugging)
 */
inline const char* ErrorCodeToString(ErrorCode code) {
  switch (code) {
    case ErrorCode::OK: return "OK";
    case ErrorCode::CANBUS_ERROR: return "CANBUS_ERROR";
    case ErrorCode::PLANNER_PARKING_COLLISION_ERROR: return "PLANNER_PARKING_COLLISION_ERROR";
    case ErrorCode::PLANNER_PARKING_PATHGENERATOR_ERROR: return "PLANNER_PARKING_PATHGENERATOR_ERROR";
    case ErrorCode::CONTROL_ERROR: return "CONTROL_ERROR";
    default: return "UNKNOWN_ERROR_CODE";
  }
}

